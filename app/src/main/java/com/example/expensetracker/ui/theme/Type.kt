// Default fallback typography
val Typography = getStandardTypography()

@Composable
fun getAdaptiveTypography(): Typography {
    val configuration = LocalConfiguration.current
    val screenWidth = configuration.screenWidthDp

    return remember(screenWidth) {
        when {
            screenWidth < 360 -> getCompactTypography()
            screenWidth < 400 -> getStandardTypography()
            else -> getExpandedTypography()
        }
    }
}

